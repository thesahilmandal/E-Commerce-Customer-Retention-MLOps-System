def test_model_loader_run_success(mock_pipeline_context, dummy_model_state_path):
    """
    Tests the complete happy path of the Model Loader execution workflow.
    Validates S3 fetching, state pointer parsing, artifact downloading, and metadata generation.
    """

    def s3_download_side_effect(s3_uri, local_path):
        # Simulate downloading the pointer file from S3
        if s3_uri.endswith("model_state.json"):
            shutil.copy(dummy_model_state_path, local_path)
        else:
            # Simulate downloading artifacts by writing dummy data (needed for os.path.getsize)
            with open(local_path, "w", encoding="utf-8") as f:
                f.write("mock_artifact_content")

    mock_pipeline_context.s3_sync.download_file.side_effect = s3_download_side_effect

    loader = ModelLoader(context=mock_pipeline_context)
    artifact = loader.run()

    # Validate output artifact
    assert isinstance(artifact, ModelLoaderArtifact)
    assert artifact.champion_run_id == "champion_run_456"
    assert os.path.exists(artifact.model_file_path)
    assert os.path.exists(artifact.schema_file_path)
    assert os.path.exists(artifact.metadata_file_path)

    # Validate S3 calls (1 for pointer + 4 for artifacts)
    assert mock_pipeline_context.s3_sync.download_file.call_count == 5

    # Validate metadata content
    with open(artifact.metadata_file_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)
        assert metadata["pipeline_stage"] == "Model Loader"
        assert metadata["inference_run_id"] == mock_pipeline_context.run_id
        assert metadata["model_provenance"]["run_id"] == "champion_run_456"
        assert "local_artifact_sizes_bytes" in metadata


