def test_model_loader_pointer_missing_keys(mock_pipeline_context, temp_workspace):
    """
    Tests that a downloaded state pointer missing required contractual keys raises an error.
    """
    malformed_state_path = temp_workspace / "malformed_model_state.json"
    malformed_data = {
        "run_id": "champion_run_456",
        # Missing other required keys like s3_model_path
    }
    with open(malformed_state_path, "w", encoding="utf-8") as f:
        json.dump(malformed_data, f)

    def s3_download_side_effect(s3_uri, local_path):
        if s3_uri.endswith("model_state.json"):
            shutil.copy(malformed_state_path, local_path)

    mock_pipeline_context.s3_sync.download_file.side_effect = s3_download_side_effect

    loader = ModelLoader(context=mock_pipeline_context)

    with pytest.raises(CustomException) as exc_info:
        loader.run()

    assert "Missing required keys" in str(exc_info.value)
    assert "s3_model_path" in str(exc_info.value)


