def test_model_loader_artifact_download_failure(
    mock_pipeline_context, dummy_model_state_path
):
    """
    Tests that if the pointer is successfully fetched but a subsequent artifact
    download fails, the process is safely aborted and an exception is raised.
    """

    def s3_download_side_effect(s3_uri, local_path):
        if s3_uri.endswith("model_state.json"):
            shutil.copy(dummy_model_state_path, local_path)
        else:
            raise Exception(f"Failed to download artifact: {s3_uri}")

    mock_pipeline_context.s3_sync.download_file.side_effect = s3_download_side_effect

    loader = ModelLoader(context=mock_pipeline_context)

    with pytest.raises(CustomException) as exc_info:
        loader.run()

    assert "Failed to download" in str(exc_info.value)
    # 1 for pointer + 1 for the first artifact which immediately fails
    assert mock_pipeline_context.s3_sync.download_file.call_count == 2


